# =============================================================================
# Synthetic twin experiment: assimilation of SYNTHETIC ERT data (NC or HC) with pyCATHY
# =============================================================================
# nb5 (real data, NC) turned into a parametrised driver. What changed w.r.t. nb5 (everything else,
# including the order of the sections, is nb5):
#   - CLI (case, scenario, DA type, NENS, seed, inflation, obs error, bias, ...)  [section 0]
#   - case configuration from model_config.py (NC = nb1, HC = nb2): irrigation start, soil table,
#     zones, ERT paths; STABILIZE_PERIOD and IRR_START_HOUR follow the case (NC 3 h, HC 2 h)
#   - observations = synthetic .tldat of nb6 (data/3d/synthetic/<case>/procdata); the survey times
#     are read from truth_<case>.pkl (so a dense synthetic schedule works), else from the real schedule
#   - scenarios generated by make_scenarios.py (NC 'material', HC 'zone_material'), prior biased
#     by model_config.biased_overrides unless --prior-bias none
#   - ERT_DATA_ERR = 5 % = the noise of nb6; forward noise ALWAYS 0 (fwdNoiseLevel = fwdNoiseAbs = 0,
#     the pyGIMLi default noiseAbs would add unseeded noise to every member)
#   - unique run name SYN_<case>_<scenario>_<da>_N<nens>_s<seed>[_noDA]; prior cache in cache/;
#     run_meta.json (config + checks) next to the results
# Needs the pyCATHY fixes of pycathy_twin_fixes (nodal porosity, zone_material, Ks, c-lite).
#
#   python da_ert_synthetic.py --case NC --scenario ic_VGP_upd --da-type enkf --nens 100 --seed 42
#   python da_ert_synthetic.py --case HC --scenario ic_Ks_upd --prior-bias none --no-da   (open loop)
# Run from the notebook/ folder (ROOT = '../'), after nb6 for the same case / delta.
