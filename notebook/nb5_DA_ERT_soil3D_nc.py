# Drop the quadrupoles flagged bad by the processing (err = 999.99 placeholder): they are
# ~40% of the file (the valid ones match the 2841-line .shm) and must not be assimilated.
# ERT_MIN_ABS_R > 0 also drops near-zero-potential quadrupoles (unstable forward response).
ERT_MIN_ABS_R = 0.0
ERT_FWD_TOL = 0.10      # None = keep every quadrupole; see unreliable_quadrupoles (nc_model.py)
ERT_MIN_KEEP_FRAC = 0.5  # abort if fewer than this share of the error-valid quadrupoles survives the forward test
ERT_SKIP_FAILED = True   # True = a survey failing the forward test is SKIPPED (not assimilated), the run goes on
ERT_STRICT = True        # (only if ERT_SKIP_FAILED=False) True (default) = stop if the forward test fails; False = report and continue (exploration only)
