def choose_ert_frame():
    """Return (signs, shift, origin): the transform ERT frame -> CATHY frame.
    Every candidate is tested with check_ert_cathy_alignment on the electrodes AND the pygimli
    mesh nodes (electrodes must sit on mesh nodes, inside the CATHY volume, top = soil surface)."""
    z_signs = (1, -1) if ERT_Z_SIGN is None else (ERT_Z_SIGN,)
    cands = []
    if ERT_MESH_SHIFT is not None:
        cands += [((1, 1, sz), tuple(ERT_MESH_SHIFT), 'manual') for sz in z_signs]
    else:
        legacy = (X / 2 - 0.5, Y / 2 - 0.5, ELEVATION)
        cands += [((1, 1, sz), legacy, 'legacy (farming_DA_ERT3d.py)') for sz in z_signs]
        if ERT_AUTO_ALIGN:
            sg, sh, _ov = suggest_frame(elecs, meshERT_raw.points, cathy_bounds, z_signs)
            cands.append((sg, sh, 'auto (array centred on the plot, surface = CATHY top)'))
    log = []
    for signs, shift, origin in cands:
        rep_ = check_ert_cathy_alignment(
            transform_points(elecs, signs, shift), cathy_bounds,
            pg_points=transform_points(meshERT_raw.points, signs, shift), on_fail='ignore')
        if rep_['ok']:
            return signs, shift, origin
        log.append(f"  * {origin}, signs={signs}, shift={np.round(shift, 3).tolist()}: "
                   + "; ".join(rep_['problems']))
    raise ERTAlignmentError(
        "no ERT->CATHY frame passes the alignment check; tried:\n" + "\n".join(log) +
        "\nSet ERT_MESH_SHIFT / ERT_Z_SIGN from the field layout (or view with SHOW_MESH_ALIGNMENT).")


