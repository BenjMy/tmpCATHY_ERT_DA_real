for f, _ts, _at in zip(ert_files, obs_stamps, assim_times):
    dst = os.path.join(_filt_dir, os.path.basename(f))
    # 1) drop the rows flagged bad by the processing (err = 999.99) -> dst
    n_valid, n_tot = filter_tldat(f, dst, min_abs_r=ERT_MIN_ABS_R)
    n_keep = n_valid
    if ERT_FWD_TOL is not None:
        # 2) homogeneous-medium test of the forward on the SAME mesh and quadrupoles as the DA.
        #    _bad is indexed on the rows of dst, so it must be applied to dst (not to the raw file f).
        _bad = unreliable_quadrupoles(ERT_MESH_FILE, dst, tol=ERT_FWD_TOL)
        _tmp = dst + '.tmp'
        n_keep, _ = filter_tldat(dst, _tmp, min_abs_r=0.0, drop=_bad)
        os.replace(_tmp, dst)
        print(f"  {os.path.basename(f)}: {int(_bad.sum())} quadrupoles dropped "
              f"(forward error > {ERT_FWD_TOL:.0%} in a homogeneous medium)")
    print(f"  {os.path.basename(f)}: {n_keep}/{n_tot} quadrupoles kept ({n_valid} error-valid)")
    if n_keep < ERT_MIN_KEEP_FRAC * n_valid:
        _msg = (f"{os.path.basename(f)}: only {n_keep} of {n_valid} valid quadrupoles pass the forward test "
                f"(< {ERT_MIN_KEEP_FRAC:.0%}): check the forward mesh / electrodes (small mesh, boundary effects, "
                "wrong mesh file) before assimilating")
        if ERT_SKIP_FAILED:
            print("  SKIPPED survey (not assimilated): " + _msg)
            _skipped.append(os.path.basename(f))
            os.remove(dst)                 # keep ert_filtered/ in step with the assimilated surveys
            continue
        if ERT_STRICT:
            raise AssertionError(_msg)
        _fwd_problems.append(_msg)
        try:                               # print a full error but keep running
            raise AssertionError(_msg)
        except AssertionError:
            traceback.print_exc()
    _filtered.append(dst)
    _kept_stamps.append(_ts)
    _kept_times.append(_at)
