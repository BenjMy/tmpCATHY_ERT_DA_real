# perturbate() validates the scenario (pyCATHY.DA.scenario.validate_scenario: unknown
# names, list lengths, bounds, ...) and builds one entry per scalar / layer. The van
# Genuchten parameters use the 'layers' control: keys SATCELL_VG0..14, n_VG0..14,
# thetar_VG0..14 (0-based layer from the top), written to VGPSATCELL / VGNCELL / VGRMCCELL.
#
# Archie parameters (a_Archie, m_Archie, n_Archie) are scalars drawn by perturbate.Archie_pert_rules,
# which now uses the per_bounds / sampling_type of the scenario entry (the old fixed truncations
# a in [0, 2.5], m and n in [1.3, 3] are only the default when the entry has no bounds).
# Each member then gets its own Archie value in the ERT forward (DA.update_archie_parameter).
#
# FIXME (future fix, not done here): mutual correlation between the VGP.
#   perturbate() draws every VGP entry independently: alpha (SATCELL_VG), n_VG and
#   thetar_VG of a layer are uncorrelated in the prior, and the layers of one material
#   (0-5, 6-8, 9-14 in nc_model.py) are independent too. Real VGP are correlated, and
#   the EnKF only sees the correlation the prior ensemble contains. Refactor
#   pyCATHY/DA/perturbate.py (perturbate_parm_by_layers / process_perturbation_block, or a
#   new joint-sampling step) to draw the VGP of a layer (or material) jointly, as in
#   Botto, Belluco & Camporese (2018), HESS 22, 4251-4266,
#   https://hess.copernicus.org/articles/22/4251/2018/ : Johnson transforms (the existing
#   transf_type: lognormal / log-ratio / hyperbolic) to normal variables, a covariance matrix
#   between the transformed VGP (Carsel & Parrish 1988 statistics; e.g. a 'per_corr' entry
#   in the scenario), ensemble drawn with its Cholesky factor, the transformed VGP in the
#   EnKF state vector, then back-transformed. Also check the update keeps the correlation.
#   Same note in make_scenario_nc_VGP.py.
