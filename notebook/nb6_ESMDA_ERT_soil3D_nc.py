# =============================================================================
# Agripolis 3D hydro (NC): ES-MDA (smoother) on ERT data with pyCATHY
# =============================================================================
# Smoother version of nb5_DA_ERT_soil3D_nc.py (EnKF/PF): the SAME model, ERT data, frame
# alignment, quadrupole filtering and perturbation scenario, but the parameters are estimated
# with ES-MDA (Emerick & Reynolds 2013, pyCATHY.DA.esmda) instead of a sequential filter:
#   - the whole period is simulated from t = 0 at every iteration (no restart from an
#     analysed state), the ERT forward is run on the state of EVERY survey time;
#   - the same data are assimilated ESMDA_N_ITER times with R inflated by alpha_i
#     (sum 1/alpha_i = 1), the parameters are updated after each iteration;
#   - only PARAMETERS are updated ('St. var.' in listUpdateParm is ignored); the initial
#     condition is estimated through its parameter 'ic'.
# DA.run_DA_esmda is EXPERIMENTAL: not yet validated on a real CATHY run. Start with a small
# case (NENS = 16-32, ESMDA_N_ITER = 2, few surveys) and read the 'ES-MDA' guide
# (doc/content/DA_guides/esmda.rst), section 'What to check on a first run'.
#
# Differences with nb5 (everything else is unchanged):
#   - section 0 : ESMDAConfig instead of the EnKF/PF options; OBS_TIME_CONVENTION
#   - section 4 : survey time stamps (see the note on the two conventions there); the
#                 sequential-DA time-alignment check is replaced by a smoother check
#   - section 6 : run_DA_esmda
#   - section 7 : misfit / parameter diagnostics
#
# --- original header of nb5 ----------------------------------------------------
# Successor of farming_DA_ERT3d.py (+ farming_DA_Scenario.py, utils.py), rebuilt
# on top of nc_model.py and the scenario-file workflow of nb4_DA_soil3D_nc.py.
#
#   1. DA project with the nb1 model (biased prior ensemble)
#   2. Archie mapping operator (saturation -> resistivity)
#   3. forward ERT mesh (pygimli vtk) re-positioned on the CATHY mesh
#   4. ERT observations (one pygimli .data file per assimilation time)
#   5. ES-MDA with list_assimilated_obs='all' (the ERT surveys)
#
# Set WITH_DA = False for the open-loop run (data error = 1e99, as in
# DA_ERT_part2_runDA.py).
#
# Refactored (2026-10) for the DA code of pyCATHY commit 083f0ac:
#   - options through DAConfig / AnalysisConfig (the keyword form is deprecated;
#     perturb_obs must go through AnalysisConfig, as a keyword it does nothing)
#   - observation time stamps = START of the model window (see section 4)
#   - ERT error as a percentage (data_err_unit='percent'), forward noise 0
#     (it is already in R and in the perturbed observations), R stored diagonal
#   - perturbation scenario read from scenario_nc_ERT.toml (generated by
#     make_scenario_nc_VGP.py, includes the van Genuchten parameters, VGP),
#     validated with pyCATHY.DA.scenario before the ensemble is built
#
# ERT <-> CATHY frames (2026-10-19): the pygimli mesh/electrodes and the CATHY mesh use different
# conventions (origin, z sign). Previously only the mesh was shifted and the RAW electrodes were
# passed to the forward model -> electrodes off the mesh, ~50% negative geometric factors,
# rhoa far outside the model range, EnKF diverging (all members rejected at cycle 5).
# Now ONE transform p_cathy = p_ert*signs + shift is applied to mesh, electrodes and the
# electrode blocks of the data files, and the result is verified (ert_alignment.py) BEFORE any
# model run; a misaligned geometry stops the script.
#
# NOTE: the ERT block follows DA_ERT_part2_runDA.py (read_observations with
# data_type='ERT' + metadata dict). Check the keys against your pyCATHY version.
